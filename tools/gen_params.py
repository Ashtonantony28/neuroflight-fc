#!/usr/bin/env python3
"""Generate fw/core/include/nf/vehicle_params.hpp from config/vehicle_nominal.yaml.

Usage:
    python3 tools/gen_params.py            # (re)write the header
    python3 tools/gen_params.py --check    # exit 1 if the header is stale
    python3 tools/gen_params.py --yaml X --out Y

Every top-level key becomes `nf::vehicle::k<CamelCase>`. Keys ending in `_hz`
are emitted as `int`, everything else as `float` (lists as `float[N]`).
Never hand-edit the generated header (INTERFACES.md section 3).
"""
import argparse
import hashlib
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_YAML = ROOT / "config" / "vehicle_nominal.yaml"
DEFAULT_OUT = ROOT / "fw" / "core" / "include" / "nf" / "vehicle_params.hpp"


def camel(key: str) -> str:
    return "k" + "".join(p[:1].upper() + p[1:] for p in key.split("_"))


def flit(v) -> str:
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        raise ValueError(f"non-numeric value {v!r}")
    s = repr(float(v))
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def render(yaml_path: pathlib.Path) -> str:
    raw = yaml_path.read_bytes()
    data = yaml.safe_load(raw)
    if not isinstance(data, dict):
        raise ValueError("vehicle yaml must be a mapping")
    digest = hashlib.sha256(raw).hexdigest()[:16]
    lines = [
        "// GENERATED by tools/gen_params.py from config/vehicle_nominal.yaml -- DO NOT EDIT.",
        f"// source sha256[:16] = {digest}",
        "#pragma once",
        "",
        "namespace nf {",
        "namespace vehicle {",
        "",
    ]
    for key, val in data.items():
        name = camel(str(key))
        if isinstance(val, list):
            body = ", ".join(flit(x) for x in val)
            lines.append(f"inline constexpr float {name}[{len(val)}] = {{{body}}};")
        elif str(key).endswith("_hz"):
            if float(val) != int(val):
                raise ValueError(f"{key} must be an integer")
            lines.append(f"inline constexpr int {name} = {int(val)};")
        else:
            lines.append(f"inline constexpr float {name} = {flit(val)};")
    lines += ["", "}  // namespace vehicle", "}  // namespace nf", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--yaml", type=pathlib.Path, default=DEFAULT_YAML)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="fail if --out is not up to date")
    args = ap.parse_args()
    text = render(args.yaml)
    if args.check:
        cur = args.out.read_text() if args.out.exists() else ""
        if cur != text:
            print(f"{args.out} is stale; run tools/gen_params.py", file=sys.stderr)
            return 1
        print(f"{args.out} up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text() != text:
        args.out.write_text(text)
        print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
