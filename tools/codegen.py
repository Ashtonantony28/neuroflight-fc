#!/usr/bin/env python3
"""Emit C++ (`.hpp` + `.cpp`) for a quantized `*.nfpol.json` (codegen target:
fw/core/include/nf/policy.hpp).

    python3 tools/codegen.py policy.q.nfpol.json --out-dir DIR [--stem nf_policy_gen] [--namespace nf_gen]

Generates, in namespace <ns>:
    extern const nf::FloatModel kPolicyF32;   // float32 model
    extern const nf::Int8Model  kPolicyI8;    // int8 model (§7)
    constexpr uint32_t kPolicyF32Crc, kPolicyI8Crc;
    constexpr const char kPolicyName[];
Float literals are printed with `%.9g` (+ `f`), which round-trips every
float32 exactly; the CRC32s are computed with zlib over the float32/int
little-endian bytes in the order documented in policy.hpp, so a lossy
literal would be caught by `nf::policy_crc32()` at arming time.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import zlib

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from golden import Int8Arrays  # noqa: E402

F32 = np.float32


# --------------------------------------------------------------------------- CRC (policy.hpp rule)
def float_arrays(pol: dict):
    mean = np.asarray(pol["obs_mean"], F32)
    std = np.asarray(pol["obs_std"], F32)
    layers = [(np.asarray(L["W"], F32), np.asarray(L["b"], F32)) for L in pol["layers"]]
    return mean, std, layers


def crc_float(pol: dict) -> int:
    mean, std, layers = float_arrays(pol)
    c = zlib.crc32(mean.astype("<f4").tobytes())
    c = zlib.crc32(std.astype("<f4").tobytes(), c)
    for W, b in layers:
        c = zlib.crc32(W.astype("<f4").tobytes(), c)
        c = zlib.crc32(b.astype("<f4").tobytes(), c)
    return c & 0xFFFFFFFF


def crc_int8(q: Int8Arrays) -> int:
    c = zlib.crc32(q.obs_mean.astype("<f4").tobytes())
    c = zlib.crc32(q.obs_std.astype("<f4").tobytes(), c)
    n = len(q.layers)
    for l, L in enumerate(q.layers):
        c = zlib.crc32(L.W_q.astype("i1").tobytes(), c)
        c = zlib.crc32(L.b_q.astype("<i4").tobytes(), c)
        if l + 1 < n:
            c = zlib.crc32(L.M.astype("<i4").tobytes(), c)
            c = zlib.crc32(L.S.astype("u1").tobytes(), c)
            c = zlib.crc32(L.lut.astype("i1").tobytes(), c)
        else:
            c = zlib.crc32(L.s_w.astype("<f4").tobytes(), c)
    return c & 0xFFFFFFFF


# --------------------------------------------------------------------------- literal formatting
def flit(v) -> str:
    v = F32(v)
    if not np.isfinite(v):
        raise ValueError(f"non-finite float in model: {v}")
    s = "%.9g" % float(v)
    if not re.search(r"[.eE]", s):
        s += ".0"
    assert F32(float(s)) == v or (v == 0 and float(s) == 0)
    return s + "f"


def ilit32(v: int) -> str:
    v = int(v)
    return "(-2147483647 - 1)" if v == -(2 ** 31) else str(v)


def fmt_array(ctype: str, name: str, vals, fmt, per_line: int = 8) -> str:
    vals = list(vals)
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(fmt(v) for v in vals[i:i + per_line]) + ",")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


# --------------------------------------------------------------------------- emit
def generate(pol: dict, stem: str = "nf_policy_gen", ns: str = "nf_gen", name: str = "policy",
             source: str = "") -> tuple[str, str, dict]:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*(::[A-Za-z_][A-Za-z0-9_]*)*", ns):
        raise ValueError(f"bad namespace {ns!r}")
    q = Int8Arrays.from_policy(pol)
    mean, std, flayers = float_arrays(pol)
    n = len(flayers)
    obs_dim, act_dim = len(mean), flayers[-1][0].shape[0]
    cf, ci = crc_float(pol), crc_int8(q)
    for l, L in enumerate(pol["layers"]):
        if L["act"] not in ("tanh", "none"):
            raise ValueError(L["act"])
    acts = ["nf::Act::Tanh" if L["act"] == "tanh" else "nf::Act::None" for L in pol["layers"]]

    hdr = f"""// AUTO-GENERATED by tools/codegen.py -- do not edit.
// source: {source}
#pragma once

#include <cstdint>

#include "nf/policy.hpp"

namespace {ns} {{

constexpr const char kPolicyName[] = "{name}";
constexpr uint32_t kPolicyF32Crc = 0x{cf:08X}u;
constexpr uint32_t kPolicyI8Crc = 0x{ci:08X}u;
extern const nf::FloatModel kPolicyF32;
extern const nf::Int8Model kPolicyI8;

}}  // namespace {ns}
"""
    out = [f"// AUTO-GENERATED by tools/codegen.py -- do not edit.\n// source: {source}\n"
           f'#include "{stem}.hpp"\n\nnamespace {ns} {{\nnamespace {{\n\n']
    out.append(fmt_array("float", "kMean", mean, flit))
    out.append(fmt_array("float", "kStd", std, flit))
    for l, (W, b) in enumerate(flayers):
        out.append(fmt_array("float", f"kW{l}", W.ravel(), flit))
        out.append(fmt_array("float", f"kB{l}", b, flit))
    out.append(f"static const nf::FloatLayer kLayers[{n}] = {{\n")
    for l, (W, b) in enumerate(flayers):
        out.append(f"    {{{W.shape[1]}, {W.shape[0]}, kW{l}, kB{l}, {acts[l]}}},\n")
    out.append("};\n\n")
    for l, L in enumerate(q.layers):
        out.append(fmt_array("int8_t", f"kQW{l}", L.W_q.ravel(), str, 16))
        out.append(fmt_array("int32_t", f"kQB{l}", L.b_q, ilit32))
        if l + 1 < n:
            out.append(fmt_array("int32_t", f"kM{l}", L.M, ilit32))
            out.append(fmt_array("uint8_t", f"kS{l}", L.S, str, 16))
            out.append(fmt_array("int8_t", f"kLut{l}", L.lut, str, 16))
        else:
            out.append(fmt_array("float", f"kSw{l}", L.s_w, flit))
    out.append(f"static const nf::Int8Layer kQLayers[{n}] = {{\n")
    for l, L in enumerate(q.layers):
        o, i = L.W_q.shape
        if l + 1 < n:
            out.append(f"    {{{i}, {o}, kQW{l}, kQB{l}, kM{l}, kS{l}, kLut{l}, nullptr}},\n")
        else:
            out.append(f"    {{{i}, {o}, kQW{l}, kQB{l}, nullptr, nullptr, nullptr, kSw{l}}},\n")
    out.append("};\n\n}  // namespace\n\n")
    out.append(f"const nf::FloatModel kPolicyF32 = {{{obs_dim}, {act_dim}, {n}, kMean, kStd, kLayers, kPolicyF32Crc}};\n")
    out.append(f"const nf::Int8Model kPolicyI8 = {{{obs_dim}, {act_dim}, {n}, kMean, kStd, kQLayers,\n"
               f"                                 /*s_in=*/{flit(q.s_in)}, /*s_x_last=*/{flit(q.s_x_last)},"
               f" kPolicyI8Crc}};\n")
    out.append(f"\n}}  // namespace {ns}\n")
    return hdr, "".join(out), {"crc_f32": cf, "crc_i8": ci}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("policy", help="quantized *.nfpol.json")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--stem", default="nf_policy_gen")
    ap.add_argument("--namespace", default="nf_gen")
    ap.add_argument("--name", default=None, help="policy name string (default: file stem)")
    a = ap.parse_args(argv)
    with open(a.policy) as f:
        pol = json.load(f)
    name = a.name or os.path.basename(a.policy).split(".")[0]
    hdr, cpp, crcs = generate(pol, a.stem, a.namespace, name, os.path.basename(a.policy))
    os.makedirs(a.out_dir, exist_ok=True)
    for ext, txt in (("hpp", hdr), ("cpp", cpp)):
        with open(os.path.join(a.out_dir, f"{a.stem}.{ext}"), "w") as f:
            f.write(txt)
    print(f"wrote {a.out_dir}/{a.stem}.{{hpp,cpp}}  crc_f32=0x{crcs['crc_f32']:08X} crc_i8=0x{crcs['crc_i8']:08X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
